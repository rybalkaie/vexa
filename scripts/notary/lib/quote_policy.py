"""Ф10d (R13.2): правка не выносит расшифровку участникам.

ЗАЧЕМ. Протокол видят все участники встречи, расшифровка — только организатор
(R5.7, гейт Ф7a на портале). Но у протокола есть чёрный ход: правка. «Добавь
дословно, кто что сказал по этому спору» — и модель, которой в промпт подаётся
ПОЛНЫЙ транскрипт, послушно перенесёт прямую речь в протокол, а протокол увидят
все. Формально ни один гейт не нарушен: расшифровку никто не открывал, её просто
переписали в документ, который открыт. Один невинно звучащий реплай — и разговор
вынесен.

ПРАВИЛО. Правка, ТРЕБУЮЩАЯ новых дословных цитат из расшифровки, принимается
только от организатора встречи. От остальных — отклоняется, и человеку говорится
почему (молчаливый дроп здесь хуже отказа: участник решит, что бот сломался, и
пришлёт то же самое ещё трижды).

ЧТО ЭТО НЕ ЕСТЬ. Это не запрет править протокол и не запрет упоминать, кто что
делал. «Ольга отвечает за поставку, а не Пётр» — обычная правка, она проходит.
Ловится ровно один класс: «перепиши в протокол, что человек сказал, слово в
слово». Поэтому детектор УЗКИЙ и требует ГЛАГОЛА-действия рядом со словом про
цитату: одинокое «в расшифровке ошибка» — это исправление, а не требование цитат,
и отбивать его было бы вредительством.

ГРАНИЦА ОТВЕТСТВЕННОСТИ. Гейт стоит на ВХОДЕ (правка не записывается в окно
сбора) И на сборке (`feedback_reissue.build_edit_instruction` добавляет модели
явный запрет, когда в раунде есть правки не от организатора). Два слоя нужны
потому, что первый ловит явную формулировку, а второй — окольную: «раскрой этот
пункт подробнее» тоже может утянуть прямую речь, и запрет в промпте её удержит.

🔴 ПОВЕДЕНИЕ ВЛАДЕЛЬЦА НЕ МЕНЯЕТСЯ. У личных серий владельца организатор — он сам
(наряда нет, значит и чужого организатора нет), поэтому ЛЮБАЯ его правка проходит
как вчера. Меняется ровно одно: чужой человек в групповом чате больше не может
попросить дословные цитаты. Аварийный выключатель — `ENABLE_QUOTE_POLICY=0`.

R9: тексты правок этот модуль не логирует — только вердикт и код причины.
"""
from __future__ import annotations

import logging
import os
import re
from dataclasses import dataclass
from typing import Any, Optional

logger = logging.getLogger("notary.quote_policy")

ENABLE_ENV = "ENABLE_QUOTE_POLICY"

CODE_OK = "ok"
CODE_QUOTES_NOT_ORGANIZER = "quotes_require_organizer"

# Глагол-действие: «сделай с протоколом вот это». Без него слово про цитату —
# скорее всего описание проблемы («в расшифровке ошибка»), а не требование.
_ACTION = (
    r"(?:добав\w*|привед\w*|вставь?\w*|процитир\w*|покаж\w*|напиш\w*|включ\w*|"
    r"выдай|дай|скопир\w*|перенес\w*|распиш\w*|укаж\w*|оставь?\w*|сохран\w*|"
    r"воспроизвед\w*|верни|вернуть|нужн\w*|хочу|надо|требуется)"
)

# Предмет требования: именно ДОСЛОВНАЯ речь.
#
# 🔴 Слов-ИСТОЧНИКОВ («расшифровка», «транскрипт», «стенограмма») здесь
# намеренно НЕТ. Они встречаются в обычных правках чаще, чем в требованиях цитат:
# «в расшифровке ошибка в цифре», «в транскрипте перепутаны спикеры», «нужно
# поправить расшифровку» — это исправления, и отбивать их означало бы сломать
# фичу правок ради буквы правила. Требование цитат опознаётся по тому, что
# просят ДОСЛОВНОСТЬ, а не по тому, что упомянут источник.
_QUOTE_OBJ = (
    r"(?:дословн\w*|цитат\w*|цитир\w*|прям(?:ую|ой|ая)\s+речь\w*|verbatim|"
    r"(?:что|чт[оо])\s+(?:именно\s+)?(?:кто\s+)?сказал\w*|"
    r"кто\s+(?:что|чего)\s+(?:именно\s+)?(?:говорил|сказал)\w*|"
    r"(?:его|её|ее|их)\s+слов\w*|"
    r"слов\w*\s+в\s+слово)"
)

# Формулировки, которым глагол не нужен — они сами по себе означают «дай цитату».
_UNCONDITIONAL = re.compile(
    r"(?:\bслово\s+в\s+слово\b|\bпроцитир\w*|\bverbatim\b|\bдословн\w*\s+цитат\w*|"
    r"\bкто\s+что\s+сказал\w*)",
    re.IGNORECASE,
)

#: Насколько далеко глагол может стоять от предмета, чтобы считаться одной мыслью.
#: 80 знаков — примерно одно предложение; больше означало бы «нашли два слова в
#: разных предложениях и объявили это требованием цитат».
_WINDOW = 80

_ACTION_RE = re.compile(_ACTION, re.IGNORECASE)
_QUOTE_RE = re.compile(_QUOTE_OBJ, re.IGNORECASE)


@dataclass(frozen=True)
class Decision:
    """Вердикт по одной правке."""

    allowed: bool
    code: str = CODE_OK
    message: str = ""


ALLOWED = Decision(allowed=True)


def is_enabled() -> bool:
    """Гейт `ENABLE_QUOTE_POLICY` — ДЕФОЛТ ON (`0/false/no/off` выключают).

    Дефолт ON, в отличие от `ENABLE_PORTAL_ORDERS`: это не новая функция, которую
    обкатывают тёмным запуском, а закрытая дыра приватности. Тумблер существует
    ради отката, если детектор окажется слишком жадным на живых правках.
    """
    raw = (os.environ.get(ENABLE_ENV) or "").strip().lower()
    return raw not in ("0", "false", "no", "off")


def wants_new_quotes(text: Any) -> bool:
    """Требует ли правка НОВЫХ дословных цитат из расшифровки.

    Узко по построению: либо формулировка, которая ничего другого значить не
    может (`слово в слово`, `процитируй`), либо глагол-действие рядом со словом
    про дословную речь. «В расшифровке ошибка в цифре» — не требование.
    """
    if not isinstance(text, str) or not text.strip():
        return False
    body = text.strip()
    if _UNCONDITIONAL.search(body):
        return True
    for q in _QUOTE_RE.finditer(body):
        left = body[max(0, q.start() - _WINDOW):q.start()]
        right = body[q.end():q.end() + _WINDOW]
        if _ACTION_RE.search(left) or _ACTION_RE.search(right):
            return True
    return False


def check_edit(text: Any, *, is_organizer: bool) -> Decision:
    """Можно ли применять эту правку. Организатору — всё, остальным — без цитат."""
    if not is_enabled():
        return ALLOWED
    if is_organizer:
        return ALLOWED
    if not wants_new_quotes(text):
        return ALLOWED
    return Decision(
        allowed=False,
        code=CODE_QUOTES_NOT_ORGANIZER,
        message=(
            "Эту правку не применю: она просит перенести в протокол дословные "
            "слова из расшифровки, а расшифровка доступна только организатору "
            "встречи. Опишите, ЧТО нужно поправить по смыслу («по поставке "
            "отвечает Ольга, а не Пётр»), и я поправлю. Нужны именно цитаты — "
            "попросите организатора."
        ),
    )


