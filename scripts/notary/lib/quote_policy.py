def organizer_telegram_id(meeting_meta: Any, *, session_uid: Optional[str] = None) -> Optional[int]:
    """Телеграм организатора ЭТОЙ встречи (владельца наряда) или None.

    None означает «наряда нет» — личная серия владельца портала, и организатором
    там считается он сам (см. `is_organizer`).
    """
    try:
        from notary.lib import delivery_route  # noqa: PLC0415

        route = delivery_route.route_for_meeting(
            meeting_meta if isinstance(meeting_meta, dict) else {},
            session_uid=session_uid,
        )
    except Exception:  # noqa: BLE001 — маршрут недоступен → наряда не знаем
        return None
    if route.is_owner_legacy:
        return None
    return route.owner_user_id


def is_organizer(
    user_id: Any,
    meeting_meta: Any,
    *,
    owner_chat: Any = None,
    session_uid: Optional[str] = None,
) -> bool:
    """Организатор ли этот телеграм-аккаунт для этой встречи.

    * Наряда нет (личная серия) → организатор ровно один: владелец портала.
      Его правки, как и вчера, проходят любые.
    * Наряд есть → организатор тот, чей это наряд. Владелец портала при этом
      организатором ЧУЖОЙ встречи не становится: администратор он на портале, а
      здесь речь о том, кому разрешено выносить дословную речь наружу.
    """
    uid = user_id if isinstance(user_id, int) and not isinstance(user_id, bool) else None
    organizer = organizer_telegram_id(meeting_meta, session_uid=session_uid)
    if organizer is None:
        owner = owner_chat if isinstance(owner_chat, int) and not isinstance(owner_chat, bool) else None
        return owner is not None and uid == owner
    return uid is not None and uid == organizer


def edits_have_outsider(edits: Any) -> bool:
    """Есть ли в раунде хоть одна правка НЕ от организатора.

    Отсутствие поля `is_organizer` (правки, записанные до Ф10d) трактуется как
    «организатор»: старые правки собраны в мире, где автор мог быть только
    владельцем, и задним числом объявлять их чужими значило бы урезать протоколы
    прошлых встреч на перевыпуске.
    """
    for e in edits or []:
        if isinstance(e, dict) and e.get("is_organizer") is False:
            return True
    return False


