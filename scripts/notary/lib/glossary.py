"""Доменный глоссарий проекта (FU-11).

Два слоя коррекции терминов, которые Speechmatics/LLM систематически перевирали
на боевых протоколах (разбор ОС команды 02–03.06):

  1. **Подсказка в промпт генерации** (`PROJECT_GLOSSARY_PROMPT_BLOCK`) — список
     канонических доменных написаний + правило «слово, похожее по звучанию на
     термин из списка, — это ошибка ASR, пиши термин». Подмешивается в
     system-prompt `generate_protocol`.

  2. **Детерминированный пост-проход** (`apply_glossary_corrections`) — узкий,
     высокоточный словарь замен по СГЕНЕРИРОВАННОМУ протоколу: ловит остаточные
     перевирания, которые пробились мимо STT-словаря и подсказки.

Разделение ответственности (важно — не дублировать вслепую):
  • Однословные неоднозначные ошибки («следов»→«лиды», «летнее»→«палетное» как
    одиночное слово) лечатся на УРОВНЕ STT-словаря (`config/speechmatics-vocab.json`,
    там уже есть sounds_like), а НЕ слепой заменой в тексте — иначе затрём
    легитимные «следов»/«летнее» (по следам, летнее меню).
  • Пост-проход держим КОНСЕРВАТИВНЫМ: только токены/биграммы, которые в этом
    домене не имеют легитимного значения («Гарсия», «летнее хранение»). Список
    задуман РАСТУЩИМ — пополняется из правок сотрудников (FU-11: «источник
    терминов — накапливать из правок»).

Источник терминов: разбор протокола координации 02.06 + `~/Projects/me/people.md`
+ `config/speechmatics-vocab.json`.
"""

from __future__ import annotations

import re

# --- Слой 1: подсказка в промпт генерации -------------------------------------
#
# Канонические написания доменных терминов. Расширения даём ТОЛЬКО там, где
# уверены (РСЯ/ЭДО/СТМ — отраслевой стандарт); для ДТ/ВКЛ/YME — оставляем токен
# как есть, не выдумывая расшифровку (правило репо «не придумывай факты»).
PROJECT_GLOSSARY_PROMPT_BLOCK = """Глоссарий проекта (доменные термины — пиши их ТОЧНО так):

- Компании и бренды: Anzhee, МПервый, ENVYTON, ALTRONIX, ENVONIX, Сценалогия, Dealer 360, YME, OZON.
- Аббревиатуры: РСЯ (рекламная сеть Яндекса), ЭДО (электронный документооборот), СТМ (собственная торговая марка), ДТ, ВКЛ, КТК (код контейнера, формат «NNNктк», напр. 059ктк).
- Склад и логистика: палетное хранение, паллет, коды контейнеров.
- Финансы: ковенанта.
- Маркетинг и продажи: лиды, лид (маркетинговые обращения — НЕ «следы»/«следов»), 1С, Битрикс24.

Правило: если в транскрипте встретилось слово, похожее ПО ЗВУЧАНИЮ на термин из списка, — это почти всегда ошибка распознавания речи. Используй правильный термин:
- «Гарсия» → РСЯ;
- «летнее хранение» → палетное хранение;
- «следы», «следов» → лиды, лидов;
- галлюцинации брендов вместо чисел (напр. «Audition» вместо «18 ед.») — НЕ выдумывай бренд, оставь число/смысл из контекста реплики.
Не добавляй термины, которых в транскрипте нет. Глоссарий — про написание уже сказанного, а не повод дописать."""


# --- Слой 2: детерминированный пост-проход по протоколу ------------------------
#
# Каждая запись — (compiled regex, replacement). Только ВЫСОКОТОЧНЫЕ замены:
# токен/биграмма без легитимного значения в этом домене. Расширять из правок
# сотрудников. Намеренно НЕ включены одиночные «следов»/«летнее» — см. модульный
# docstring (риск затереть легитимный текст; их ловит STT-словарь).
_PROTOCOL_REPLACEMENTS: list[tuple[re.Pattern, str]] = [
    # «Гарсия»/«Гарсии»/«Гарсию»… → РСЯ (в домене фамилия Гарсия не встречается).
    (re.compile(r"\bГарси[яиюейё]\b", re.IGNORECASE), "РСЯ"),
    # «летнее хранение» → «палетное хранение» (складской термин). Биграмма
    # безопасна: «летнее хранение» само по себе бессмысленно.
    (re.compile(r"\bлетнее(\s+)хранение\b", re.IGNORECASE), r"палетное\1хранение"),
    (re.compile(r"\bлетнего(\s+)хранения\b", re.IGNORECASE), r"палетного\1хранения"),
]


def apply_glossary_corrections(text: str) -> str:
    """Пост-проход замен доменных терминов по сгенерированному протоколу (FU-11).

    Идемпотентна (повторный прогон ничего не меняет — все замены уже применены).
    Консервативна: только записи из `_PROTOCOL_REPLACEMENTS`. Пустой/None-вход
    возвращает как есть.
    """
    if not text:
        return text
    out = text
    for pattern, replacement in _PROTOCOL_REPLACEMENTS:
        out = pattern.sub(replacement, out)
    return out
