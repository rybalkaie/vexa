def parse_request_json(raw: str) -> Optional[dict]:
    """Сырой ответ Claude → нормализованная структура или None на структурном сбое
    (→ фолбэк на регулярку). Всё, что не распознано как явное «send», становится
    «none»: молчание безопаснее ложной отправки документа в рабочий чат."""
    if not raw or not raw.strip():
        return None
    s = raw.strip()
    if s.startswith("```"):
        s = re.sub(r"^```(?:json)?\s*", "", s)
        s = re.sub(r"\s*```$", "", s).strip()
    start = s.find("{")
    if start < 0:
        return None
    try:
        parsed, _end = json.JSONDecoder().raw_decode(s[start:])
    except (json.JSONDecodeError, ValueError):
        return None
    if not isinstance(parsed, dict):
        return None
    intent = parsed.get("intent")
    intent = intent if intent in _VALID_INTENTS else "none"
    artifact = parsed.get("artifact")
    artifact = artifact if artifact in _VALID_ARTIFACTS else "unknown"
    why = parsed.get("why")
    why = re.sub(r"\s+", " ", str(why or ""))[:200].strip()
    return {"intent": intent, "artifact": artifact, "why": why}


def _ai_timeout() -> int:
    """Таймаут ИИ-яруса (сек): env `SEND_ARTIFACT_AI_TIMEOUT`, иначе таймаут сплиттера,
    и в ЛЮБОМ случае не больше `_AI_TIMEOUT_CAP` — вызов сидит в цикле обработки
    сообщений. Явную ручку тоже режем потолком: она заведена как аварийный рубильник
    «сделать короче», а не способ разрешить листенеру стоять дольше."""
    raw = (os.environ.get("SEND_ARTIFACT_AI_TIMEOUT") or "").strip()
    if raw:
        try:
            v = int(raw)
            if v > 0:
                return min(v, _AI_TIMEOUT_CAP)
        except (TypeError, ValueError):
            pass
    try:
        from . import mixed_reply_split as mrs  # noqa: PLC0415 (ленивый импорт)
        return min(mrs._split_timeout(), _AI_TIMEOUT_CAP)
    except Exception:  # noqa: BLE001 — недоступен сплиттер → свой потолок
        return _AI_TIMEOUT_CAP


def _hard_cap() -> float:
    """Сколько секунд ГЛАВНЫЙ ПОТОК готов ждать ответ модели — потолок, который не
    пробивается окружением.

    Почему нужен отдельно от `_ai_timeout()`. Таймаут, переданный в `claude_cli`,
    подпирается снизу глобальным полом `CLAUDE_MIN_TIMEOUT` (он заведён под длинные
    встречи и на проде может стоять): прогон ревью-1 при `SEND_ARTIFACT_AI_TIMEOUT=10`
    и `CLAUDE_MIN_TIMEOUT=900` показал в subprocess 900 с — то есть четверть часа
    заморозки листенера из-за одной фразы. Здесь потолок наш и только наш: ждём в
    отдельном потоке и по его истечении отпускаем цикл (деградация — регулярка)."""
    return float(_AI_TIMEOUT_CAP)


def _call_model_capped(prompt: str, *, system: str, timeout: int,
                       model: Optional[str]) -> Optional[str]:
    """`claude --print` с ЖЁСТКИМ потолком ожидания главного потока.

    Ответ ждём в daemon-потоке и join'им на `_hard_cap()`. Потолок вышел — возвращаем
    None (caller → фолбэк на регулярку), а поток дожёвывает subprocess сам и умирает
    вместе с ним; daemon — чтобы не задерживать остановку сервиса.

    Это ПОЛУМЕРА, и она названа полумерой: сам вызов остаётся в цикле листенера
    (перенос в фоновый воркер `_reissue_executor` — отдельная работа, см. отчёт
    ремонта). Потолок гарантирует лишь то, что цена одной фразы ограничена сверху
    ЧИСЛОМ В КОДЕ, а не настройкой окружения."""
    box: dict = {}

    def _run() -> None:
        try:
            from .claude_cli import call_claude_print  # noqa: PLC0415 (ленивый импорт)
            box["raw"] = call_claude_print(prompt, system=system, timeout=timeout,
                                           model=model)
        except BaseException as e:  # noqa: BLE001 — отдаём caller'у как есть
            box["err"] = e

    th = threading.Thread(target=_run, name="send-artifact-ai", daemon=True)
    started = time.monotonic()
    th.start()
    th.join(_hard_cap())
    if th.is_alive():
        logger.warning("[send-artifact-ai] потолок ожидания %.0fs исчерпан — "
                       "отпускаю цикл листенера (фолбэк регулярка)", _hard_cap())
        return None
    if "err" in box:
        raise box["err"]
    logger.debug("[send-artifact-ai] ответ за %.1fs", time.monotonic() - started)
    return box.get("raw")


def _ai_model() -> Optional[str]:
    """Модель ИИ-яруса — та же, что у разбора reply (`MIXED_REPLY_SPLIT_MODEL`)."""
    try:
        from . import mixed_reply_split as mrs  # noqa: PLC0415 (ленивый импорт)
        return mrs._SPLIT_MODEL
    except Exception:  # noqa: BLE001
        return None


def understand_request(text: str, *, reply_surface: Optional[str] = None,
                       answer_fn=None) -> Optional[dict]:
    """ИИ-разбор просьбы → `{"intent", "artifact", "why"}` или None (модель недоступна /
    структурный сбой → caller падает на регулярку). `answer_fn(text, reply_surface)`
    инъектируется тестами вместо реального Claude (стаб НЕ зовёт `claude`).

    Никакой сбой ИИ не должен валить листенер: все исключения гасим в None."""
    if answer_fn is not None:
        try:
            res = answer_fn(text, reply_surface)
        except Exception as e:  # noqa: BLE001 — сбой стаба/границы не валит listener
            logger.warning("[send-artifact-ai] стаб разбора упал (non-fatal): %s",
                           type(e).__name__)
            return None
        return res if isinstance(res, dict) else None

    from .claude_cli import (  # noqa: PLC0415
        ClaudeCliError, ClaudeCliNotInstalled,
    )
    prompt = build_user_prompt(text, reply_surface=reply_surface)
    started = time.monotonic()
    try:
        raw = _call_model_capped(prompt, system=REQUEST_SYSTEM_PROMPT,
                                 timeout=_ai_timeout(), model=_ai_model())
    except ClaudeCliNotInstalled:
        logger.warning("[send-artifact-ai] `claude` не в PATH — разбор просьбы пропущен "
                       "(фолбэк регулярка)")
        return None
    except ClaudeCliError as e:
        logger.warning("[send-artifact-ai] CLI error: %s (фолбэк регулярка)", type(e).__name__)
        return None
    except Exception as e:  # noqa: BLE001 — сбой LLM не валит listener
        logger.warning("[send-artifact-ai] неожиданный сбой (non-fatal): %s", type(e).__name__)
        return None
    result = parse_request_json(raw)
    logger.info("[send-artifact-ai] prompt_len=%d intent=%s artifact=%s elapsed=%.1fs",
                len(prompt),
                result["intent"] if result else "parse-fail",
                result["artifact"] if result else "?",
                time.monotonic() - started)
    return result


def _detect_by_regex(t: str, *, reply_surface: Optional[str],
                     allow_bare_file: bool) -> Optional[str]:
    """Быстрый путь ISS-45: связка «глагол отправки + объект». Поведение не менялось."""
    if not _SEND_VERB.search(t):
        return None
    dig = bool(_OBJ_DIGEST.search(t))
    prot = bool(_OBJ_PROTOCOL.search(t))
    if dig and not prot:
        return "digest"
    if prot and not dig:
        return "protocol"
    if dig and prot:
        # Оба явно названы — по контексту ответа, иначе протокол (главный документ).
        return reply_surface if reply_surface in ("protocol", "digest") else "protocol"
    if allow_bare_file and _OBJ_FILE.search(t):
        # Голый «файл» — по тому, на что отвечают.
        return reply_surface if reply_surface in ("protocol", "digest") else "protocol"
    return None


def _verify_artifact(t: str, hint: Optional[str], *, reply_surface: Optional[str],
                     allow_bare_file: bool) -> Optional[str]:
    """ИИ сказал «это просьба» — КАКОЙ артефакт можно отдать, решает код по СЛОВАМ.

    Слова решают однозначно → отдаём их вариант, даже если модель назвала другой
    (верификация, а не доверие). Названы оба класса → берём подсказку модели, нет
    её — контекст ответа, нет и его — протокол (главный документ). Назван ТОЛЬКО
    неоднозначный объект («файл / версия / документ») → нужен контекст ответа:
    без него это обычная переписка людей («вышлите файл с ценами»), и вываливать
    в чат протокол встречи нельзя (инвариант Ф1 ISS-52 `allow_bare_file`).

    Голые «вопрос…/задач…/что осталось» дайджестом становятся только вместе с
    маркером просьбы (`_digest_named`) — до ремонта они шли в ветку «названо
    однозначно» и обходили инвариант Ф1 целиком (ревью-1 🔴-1). Проверка дублирует
    пред-фильтр СОЗНАТЕЛЬНО: инвариант должен держаться и если сюда придут другим
    путём."""
    prot, _dig_s, _dig_w, amb = _object_classes(t)
    dig = _digest_named(t)
    if dig and not prot:
        return "digest"
    if prot and not dig:
        return "protocol"
    if prot and dig:
        if hint in ("protocol", "digest"):
            return hint
        return reply_surface if reply_surface in ("protocol", "digest") else "protocol"
    if amb and allow_bare_file and reply_surface in ("protocol", "digest"):
        return reply_surface
    return None


def detect_artifact_request(
    text: Optional[str], *, reply_surface: Optional[str] = None,
    allow_bare_file: bool = True, answer_fn=None,
) -> Optional[str]:
    """Что просят переслать: `"protocol"` | `"digest"` | `None`.

    `reply_surface` (`"protocol"`|`"digest"`|`None`) — на ЧТО отвечает человек;
    разрешает неоднозначное «пришли файл».

    `allow_bare_file` — можно ли вообще считать интентом ГОЛЫЙ объект
    «файл/версия» (без слова «протокол» и без дайджест-формулировки). Ветка
    голого объекта проектировалась под reply: контекст ответа и разрешал
    двусмысленность. Когда серия пришла НЕ из реплая, а из привязки чата
    (ISS-52), разрешать нечем, и «пришли файл с ценами» / «дайте актуальную
    версию договора» — обычная рабочая переписка людей между собой, а не
    просьба к боту. Поэтому вызыватель передаёт `allow_bare_file=is_reply`:
    без реплая голый объект даёт None, а однозначные («протокол», открытые
    вопросы/дайджест) работают как раньше.

    `answer_fn` — инъекция разбора вместо реального Claude (тесты).

    ISS-51: регулярка не ответила → зовём ИИ (только при флаге
    `ENABLE_SEND_ARTIFACT_AI` либо явном `answer_fn`) и верифицируем его ответ
    кодом. Флаг OFF / модель недоступна / пред-фильтр не пропустил → None, то
    есть ровно поведение ISS-45.

    Ремонт Ф6: пред-фильтр требует ДЕТЕРМИНИРОВАННЫЙ маркер просьбы
    (`looks_like_request`) — без него ни вызова модели, ни отправки. Формулировка
    по-прежнему свободная (маркер сильно шире словаря ISS-45), но «просьба ли
    это вообще» перестала быть решением, целиком отданным модели."""
    t = _norm(text)
    fast = _detect_by_regex(t, reply_surface=reply_surface, allow_bare_file=allow_bare_file)
    if fast:
        return fast
    if answer_fn is None and not is_enabled():
        return None                       # офлайн-фолбэк: реальный claude не зовём
    if not should_ask_ai(t, allow_bare_file=allow_bare_file, reply_surface=reply_surface):
        return None
    res = understand_request(text or "", reply_surface=reply_surface, answer_fn=answer_fn)
    if not isinstance(res, dict) or res.get("intent") != "send":
        return None
    kind = _verify_artifact(t, res.get("artifact"), reply_surface=reply_surface,
                            allow_bare_file=allow_bare_file)
    # Текст сообщения НЕ логируем (опасная тройка) — только коды разбора.
    logger.info("[send-artifact-ai] понято по смыслу: artifact=%s → kind=%s (surface=%s)",
                res.get("artifact"), kind or "-", reply_surface or "-")
    return kind
