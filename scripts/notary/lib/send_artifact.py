# -*- coding: utf-8 -*-
"""ISS-45 (детект) + ISS-51 (понимание): бот присылает протокол / открытые вопросы по
просьбе — и понимает просьбу ПО СМЫСЛУ, а не по списку глаголов.

Раньше движок разбора reply знал только два класса — «статус задачи» и «правка
текста»; просьба самому боту прислать файл не тот и не другой → фолбэк «не понял»
(владелец 23.07: «чуть-чуть шаг в сторону — и он не понимает ничего»). ISS-45 дал
УЗКИЙ детерминированный триггер: явный глагол отправки + объект.

ISS-51 (боевой случай 28.07): «Вышли актуальный файл с открытыми вопросами» — бот
промолчал. Не потому, что просьба непонятная, а потому, что «вышли» не оказалось в
списке глаголов: «пришли» есть, «вышли / выслать / шли» нет. Владелец диктует
голосом, формулировка каждый раз своя — конечный словарь глаголов проигрывает живой
речи всегда («бей крота»). Лечим тем же приёмом, что вылечил ответы на вопросы бота
([[ack_understand]], ISS-49): **ИИ решает, ПРОСЬБА ли это, детерминированный код
решает, ЧТО именно можно прислать и можно ли вообще**.

Как устроен разбор (три яруса, сверху вниз):
  1. БЫСТРЫЙ ПУТЬ — узкая регулярка ISS-45 (глагол отправки + объект). Срабатывает
     мгновенно, без сети, на самых частых формулировках. Дала ответ → ИИ не зовём.
  2. ИИ-ЯРУС — гейт `ENABLE_SEND_ARTIFACT_AI`, ДЕФОЛТ-OFF в коде: модель получает
     сообщение как ДАННЫЕ и отвечает структурой «просьба к боту прислать файл?
     какой?». Зовётся только если пред-фильтр (`should_ask_ai`) увидел И маркер
     просьбы (`looks_like_request`), И названный объект, ради которого вызов вообще
     может закончиться отправкой.
  3. ВЕРИФИКАЦИЯ КОДОМ — какой артефакт, решают СЛОВА сообщения, а не модель:
     названо «протокол/итоги встречи» → protocol, «открытые вопросы/дайджест/висяки»
     → digest, названы оба → подсказка модели/контекст ответа. Назван лишь
     неоднозначный объект («файл / версия / документ») → нужен контекст ответа,
     иначе None: без реплая «пришли файл с ценами» — обычная переписка людей, а не
     просьба к боту (находка Ф1 ISS-52).

РЕМОНТ Ф6 (после двух ревью и сквозной проверки) — три вещи, которых тут не хватало:

  • МАРКЕР ПРОСЬБЫ (`looks_like_request`) — детерминированный, ШИРЕ словаря ISS-45
    (не только глаголы: «не могу найти», «где протокол», «нужен протокол», «можно
    ещё раз»). Без него ИИ-ярус решал «просьба ли это» ЦЕЛИКОМ моделью, и между
    бытовым «у нас вопрос» / «давайте копить вопросы к следующей встрече» и
    вывалившимся в рабочий чат дайджестом стоял только промпт. Теперь голые основы
    «вопрос…/задач…» без маркера просьбы дайджестом НЕ становятся (ревью-1 🔴-1),
    и на них не тратится вызов модели (ревью-1 🟡-3: пред-фильтр пропускал 19 из 20
    бытовых фраз).

  • МАРКЕР ПРАВКИ (`looks_like_edit_request`) — ОДИНОЧНАЯ правка («поправь фамилию в
    протоколе», «в протоколе опечатка») порога `looks_edit_heavy` (≥2 маркера) не
    набирает и до ремонта доходила до модели: при её ошибке человек получал
    переприсланный протокол, а правка терялась — класс инцидента 20.07 (ревью-1
    🔴-2). Артефакт-роут теперь уступает шлюзу правок по ОДНОМУ маркеру.

  • ЖЁСТКИЙ ПОТОЛОК ОЖИДАНИЯ (`_hard_cap`) — вызов сидит в ЦИКЛЕ листенера, а
    `claude_cli` поверх переданного таймаута применяет глобальный пол
    `CLAUDE_MIN_TIMEOUT` (прогон ревью-1: в subprocess ушло 900 с). Ждём ответ в
    отдельном daemon-потоке и отпускаем главный поток по своему потолку, которого
    переменная окружения пробить не может.

Флаг OFF или модель недоступна → работает ровно ярус 1, то есть сегодняшнее
поведение ([[reissue-llm-tier-gate-default-off]]: офлайн-тесты не зовут реальный
`claude`, квота цела; на проде флаг ставится в 1 при деплое).

ЧЕГО ЭТОТ МОДУЛЬ НЕ РЕШАЕТ. Защита «не украсть чужое сообщение» живёт в роуте
листенера (`maybe_route_to_send_artifact`): гейт статус-разговора и правок +
позиция роута после ack- и до digest-роута. ИИ шире регулярки по определению
(риск 4 плана), поэтому статус-разговор и правки отсекаются ДО разбора — модель
на них даже не зовётся. Роут же решает, КОМУ уступает сообщение: уступать
некому (не реплай — статус-роуты ниже без реплая не работают) значит не
«безопасно промолчать», а «сообщение исчезло» — ровно жалоба ISS-51.

Различаем ДВА артефакта:
  • protocol — «протокол / актуальную версию / версию файла / итоги встречи»;
  • digest   — «открытые вопросы / дайджест / вопросы к встрече / список вопросов».

Опасная тройка (CLAUDE.md проекта): в промпт уходит только само сообщение как
ДАННЫЕ (anti-injection рамка); текст НЕ логируем (только коды и длины); сырой
ответ Claude НЕ персистим — наружу идёт лишь нормализованная структура.

stdlib-only на быстром пути (исполняется в listener-контексте, системный python3.9
без venv); зависимости ИИ-яруса подгружаются ЛЕНИВО внутри функций.
"""
from __future__ import annotations

import json
import logging
import os
import re
import threading
import time
from typing import Optional

logger = logging.getLogger("notary.send_artifact")

# Глагол «пришли мне»: пришли/пришлите, скинь/скиньте, сбрось, перешли, кинь, отправь,
# дай/дайте, покажи, повтори, «можешь скинуть/прислать/отправить». «ё»→«е» нормализуем.
_SEND_VERB = re.compile(
    r"(при[шс]л[иеёте]+|скин[ьте]+|сброс[ьте]+|перешл[иёе]+|кин[ьте]+|отправ|"
    # `да[йте]+` ловил «дате»/«дату»: «уточню по дате протокола» уходило быстрым
    # путём и бот молча высылал протокол (ремонт возобновления). Перечисляем формы.
    r"да(?:й|йте)\b|покаж|повтор|мож[её]шь\s+(?:скину|присла|отправ)|"
    r"мог[ул]\s+(?:бы\s+)?(?:ты\s+)?(?:скину|присла|отправ))",
    re.IGNORECASE)

# Объект — ПРОТОКОЛ. ТОЛЬКО явное слово «протокол». «версию файла / актуальную версию /
# сам файл / документ» сюда НЕ входят — фидбэк владельца 23.07: ответ на дайджест «Открытые
# вопросы» с «актуальную версию файла» бот слал протоколом, хотя слова «протокол» не было и
# отвечали на дайджест. «файл/версия» — неоднозначное, разрешается по контексту ответа ниже.
_OBJ_PROTOCOL = re.compile(r"протокол", re.IGNORECASE)

# Объект — ДАЙДЖЕСТ открытых вопросов.
_OBJ_DIGEST = re.compile(
    r"(открыт\w*\s+вопрос\w*|дайджест|список\s+вопрос\w*|вопрос\w*\s+к\s+встреч\w*|"
    r"открыт\w*\s+задач\w*)",
    re.IGNORECASE)

# Неоднозначная ссылка «файл / версия / актуальную версию» без слова протокол/дайджест —
# разрешаем по тому, на ЧТО отвечают (reply_surface); контекста нет → протокол (главный).
_OBJ_FILE = re.compile(r"(файл\w*|верси\w*|актуальн\w*\s+верси\w*)", re.IGNORECASE)


# ── ISS-51: гейт ИИ-яруса ─────────────────────────────────────────────────────
def is_enabled() -> bool:
    """Гейт `ENABLE_SEND_ARTIFACT_AI` — ДЕФОЛТ OFF В КОДЕ, как у `ENABLE_ACK_ANSWER_AI`
    ([[reissue-llm-tier-gate-default-off]]): без флага разбор просьбы остаётся на
    регулярке → офлайн-тесты не зовут реальный `claude` и квота цела (тесты подают
    разбор через `answer_fn` либо подменяют `understand_request`). На проде флаг
    ВЫСТАВЛЯЕТСЯ В 1 при деплое — иначе ISS-51 доедет выключенным и «вышли файл»
    снова не будет пониматься. ON ← `1/true/yes/on`."""
    raw = (os.environ.get("ENABLE_SEND_ARTIFACT_AI") or "").strip().lower()
    return raw in ("1", "true", "yes", "on")


_VALID_INTENTS = frozenset({"send", "none"})
_VALID_ARTIFACTS = frozenset({"protocol", "digest", "unknown"})

# Потолок длины сообщения, которое вообще имеет смысл гнать в ИИ. Просьба «вышли файл с
# открытыми вопросами» столько не занимает даже голосом; длинная простыня — это пересланный
# протокол, пачка правок или чужой текст. Разбирать её незачем, а вызовы модели стоят денег,
# квоты и СЕКУНД В ЦИКЛЕ ЛИСТЕНЕРА (разбор синхронный).
_MAX_TEXT_LEN_FOR_AI = 600

# Потолок таймаута ИИ-яруса. Разбор одной короткой фразы на haiku — это секунды, а вызов
# сидит В ЦИКЛЕ обработки сообщений: общий 120-секундный таймаут сплиттера заморозил бы
# листенер на две минуты из-за одной болтливой фразы. Деградация честная (фолбэк —
# регулярка), поэтому потолок ЖЁСТКИЙ: он режет и явный `SEND_ARTIFACT_AI_TIMEOUT`, и —
# через `_hard_cap` ниже — глобальный пол `CLAUDE_MIN_TIMEOUT`, который применяется уже
# внутри `claude_cli` и переданный таймаут поднимает (прогон ревью-1: 900 с в subprocess).
_AI_TIMEOUT_CAP = 30


# ── Маркер ПРОСЬБЫ: детерминированная страховка «а просят ли вообще» ───────────
# Зачем. На ИИ-пути «просьба ли это» решала ЦЕЛИКОМ модель, а словарь объектов ниже
# понимает голые «вопрос…/задач…». Между бытовым «у нас вопрос» / «давайте копить
# вопросы к следующей встрече» и вывалившимся в рабочий чат дайджестом стоял только
# промпт (ревью-1 🔴-1, ревью-2 🟡-4, шов S6). Этот маркер — код, а не доверие.
#
# ШИРЕ словаря ISS-45 сознательно: суть ISS-51 в том, что формулировка глагола роли не
# играет, поэтому сюда входят и не-глагольные формы просьбы («не могу найти», «где
# протокол», «нужен протокол», «можно ещё раз»). Прошедшее время НЕ маркер: «отправил в
# бухгалтерию», «выслал клиенту» — отчёт о своём действии, а не просьба к боту.
_REQUEST_EXTRA = re.compile(
    r"(?:"
    r"вышл(?:и|ите|ем)|высла(?:ть|ли)|высыла(?:й|йте)|\bшл(?:и|ите)\b|"
    r"присыла(?:й|йте)|"
    r"скин(?:ь|ьте|уть)|сброс(?:ь|ьте|ить)|перекин(?:ь|ьте|уть)|"
    r"отправ(?:ь|ьте|ить|ите|ляй)|"
    r"подел(?:ись|итесь)|"
    r"продублируй|продублируйте|дублируй|"
    r"покаж(?:и|ите)|показать|посмотрет|глян(?:ь|ем|уть)|"
    r"нуж(?:ен|на|ны)\b|"
    r"напомн(?:и|ите)|"
    r"не\s+могу\s+найти|не\s+нахожу|не\s+вижу|потеря(?:л|ли|лся|лась)|"
    r"где\s+(?:у\s+нас\s+|тот\s+|твой\s+|ваш\s+)?"
    r"(?:протокол|дайджест|файл|верси|документ|список|итог)|"
    r"мож(?:ешь|ете|но)\s+(?:ли\s+)?(?:ещ[е]\s+раз\s+)?"
    r"(?:скину|присла|отправ|показа|дать|высла|пересла|повтори|получи)|"
    r"ещ[е]\s+раз\s+(?:скин|пришл|вышл|отправ|покаж|дай)"
    r")",
    re.IGNORECASE)


# ── ФОРМА просьбы (не глагол) ─────────────────────────────────────────────────
# 🔴 Ремонт возобновления. Словарь глаголов перед моделью — это тот же список
# глаголов, из-за которого фаза и появилась: «а можно протокол?», «Бот, протокол»,
# «список открытых вопросов в студию» ни одним глаголом отправки не описываются.
# Но и одного НАЗВАННОГО объекта мало: «по протоколу испытаний всё ок» — чужой
# документ в обычной реплике, и платить за модель (а при её ошибке отдать файл)
# там не за что. Поэтому смотрим на ФОРМУ: вопрос, вежливая просьба, обращение
# к боту. Это шире любого списка глаголов и всё ещё детерминированно.
_REQUEST_SHAPE = re.compile(
    r"(?:"
    r"\?|"                                             # вопрос
    r"\bмож(?:но|ешь|ете)\b|\bпрошу\b|\bмне\s+бы\b|"
    r"\bнуж(?:ен|на|но|ны)\b|\bнадо\b|\bхотел(?:а|и)?\s+бы\b|"
    r"\bесть\s+(?:у\s+кого|где)\b|\bв\s+студию\b|"
    r"\bпожалуйста\b|\bплиз\b|\bплз\b|"
    r"^\s*бот[,!\s]|\bбот[,]\s|@\w+"                 # обращение к боту
    r")",
    re.IGNORECASE)


def looks_like_a_request_in_shape(text: Optional[str]) -> bool:
    """Похоже ли сообщение на просьбу ПО ФОРМЕ, без опоры на список глаголов."""
    t = _norm(text)
    return bool(t.strip()) and bool(_REQUEST_SHAPE.search(t))


def looks_like_request(text: Optional[str]) -> bool:
    """Есть ли в сообщении ДЕТЕРМИНИРОВАННЫЙ маркер просьбы что-то прислать/показать.

    Строго шире словаря быстрого пути: `_SEND_VERB` (ISS-45) ИЛИ `_REQUEST_EXTRA`.
    Строгое надмножество важно — иначе пред-фильтр отсёк бы формулировку, которую
    ISS-45 понимал, и контракт ISS-45 просел бы молча.

    Это НЕ понимание просьбы (её понимает модель, а «какой документ» — код по словам).
    Это ответ на вопрос «человек вообще о чём-то просит?»: если нет — ни вызова
    модели, ни отправки документа."""
    t = _norm(text)
    if not t.strip():
        return False
    return bool(_SEND_VERB.search(t) or _REQUEST_EXTRA.search(t))


# ── Маркер ПРАВКИ текста: одиночная правка тоже не наша (ревью-1 🔴-2) ─────────
# `pending_status_reply.looks_edit_heavy` ловит ПАЧКУ (≥2 маркера) — порог там оправдан
# (он защищает статус-роут от «задачу заменили, закрыто»). Для артефакт-роута цена
# ошибки другая: «поправь фамилию в протоколе» — один маркер, порога не набирает, до
# ремонта уходило в модель, и при её ошибке человек получал переприсланный протокол,
# а правка терялась (тот же класс, что инцидент 20.07). Здесь порог — ОДИН маркер.
_EDIT_HINT = re.compile(
    r"(?:"
    r"вместо\s+\w+|"
    r"попра[вн](?:ь|ьте|ить|им)|исправ(?:ь|ьте|ить|им|лен)|"
    r"замен(?:и|ите|ить|им|яй)|перепиш(?:и|ите)|"
    r"опечатк\w*|очепятк\w*|описк\w*|"
    r"не\s+так\s+(?:записан|написан|указан|понял)\w*|"
    r"(?:записан|написан|указан|сформулирован)\w*\s+(?:не\s+так|неверно|неправильно|с\s+ошибк)|"
    r"(?:неверно|неправильно|с\s+ошибкой)\s+(?:записан|написан|указан|сформулирован)\w*|"
    r"ошибк[аи]\s+в\s+(?:протокол|списк|дайджест|фамили|назван|дат)\w*"
    r")",
    re.IGNORECASE)


# ── ПОПУТНОЕ упоминание статуса против ОТЧЁТА о статусе ───────────────────────
# Гейт роута уступает статус-роутам. Но в живой речи просьба и статус ходят в одной
# фразе, и это ДВА РАЗНЫХ случая:
#
#   отчёт    «пришли протокол — по второй задаче всё сделано»   ← человек ДОКЛАДЫВАЕТ
#   попутно  «пришли протокол, я не помню, что мы решили»       ← человек ОБЪЯСНЯЕТ,
#                                                                 зачем просит
#
# Отчёт уступаем всегда: потерянный статус не вернуть, а файл попросят ещё раз.
# Попутное упоминание — не отчёт: уступать там нечему, а без реплая уступка = тишина
# (прогон ревью-2: так гасились 6 из 10 живых просьб). Различаем детерминированно:
# статус под «что / а то / чтобы», под сомнением («вроде», «кажется»), под
# долженствованием («должен быть закрыт»), под «не помню» или под желанием
# проверить — это причина просьбы, а не утверждение о работе.
_STATUS_INCIDENTAL = re.compile(
    r"(?:"
    r"\bчто\b|\bчего\b|\bчтобы\b|\bа\s+то\b|\bесли\b|"
    r"\bвроде\b|\bкажется\b|\bнаверное\b|\bвозможно\b|\bпохоже\b|"
    r"\bдолж(?:ен|на|но|ны)\b|"
    r"не\s+помн(?:ю|им|ит)|не\s+могу\s+вспомнить|забы(?:л|ли)|"
    r"хочу\s+\w+|хотел(?:и)?\s+бы|надо\s+(?:свериться|проверить|глянуть)|"
    r"свер(?:иться|ить|яюсь)|перепрове"
    r")",
    re.IGNORECASE)


def status_mention_is_incidental(text: Optional[str]) -> bool:
    """Статус упомянут ПОПУТНО (как причина просьбы), а не доложен?

    Ошибка в любую сторону стоит по-разному, и обе цены названы:
      • приняли отчёт за попутное → файл ушёл, статус не записан (без реплая он всё
        равно не записался бы: статус-роуты без реплая не работают);
      • приняли попутное за отчёт → бот молчит, а человек просил файл — ровно
        жалоба ISS-51."""
    t = _norm(text)
    if not t.strip():
        return False
    return bool(_STATUS_INCIDENTAL.search(t))


def looks_like_edit_request(text: Optional[str]) -> bool:
    """Похоже ли, что человек ПРАВИТ текст документа, а не просит его прислать.

    Порог — ОДИН маркер (в отличие от `looks_edit_heavy`). Ложная уступка стоит
    дёшево: человек не получит файл и попросит ещё раз. Ложный перехват стоит
    дорого: правка молча пропадёт, а в чат уедет документ, которого не просили."""
    t = _norm(text)
    if not t.strip():
        return False
    return bool(_EDIT_HINT.search(t))


# ── Классы объекта (ШИРЕ регулярки быстрого пути; только для верификации ИИ) ───
# Быстрый путь (`_OBJ_*` выше) НЕ трогаем: он отвечает за сегодняшнее поведение и
# закрыт тестами ISS-45. Эти регулярки применяются ТОЛЬКО когда ИИ уже сказал
# «это просьба к боту», и отвечают на другой вопрос — КАКОЙ из двух артефактов
# назван словами.
#
# Дайджест распался на ДВА словаря (ревью-1 🔴-1). ОДНОЗНАЧНЫЙ («открытые вопросы»,
# «дайджест», «висяки», «список задач») — так о нашем документе и говорят, его
# достаточно самого по себе. СЛАБЫЙ (голые «вопрос…», «задач…», «что осталось») —
# самые частые слова рабочего чата: они называют объект, только если рядом есть
# маркер просьбы. Иначе «у нас вопрос» и «задача не поставлена» отдавали дайджест.
_WIDE_PROTOCOL = re.compile(r"(протокол|конспект|выжимк\w*|саммари|summary)", re.IGNORECASE)
_WIDE_SUMMARY = re.compile(r"(итог\w*|резюме|сводк\w*)", re.IGNORECASE)
_WIDE_MEETING = re.compile(r"(встреч\w*|созвон\w*|планерк\w*|совещан\w*|митинг\w*)",
                           re.IGNORECASE)
_WIDE_DIGEST_STRONG = re.compile(
    r"(открыт\w*\s+(?:вопрос|задач|пункт)\w*|дайджест|висяк\w*|"
    r"список\s+(?:вопрос|задач|пункт)\w*|вопрос\w*\s+к\s+встреч\w*)",
    re.IGNORECASE)
_WIDE_DIGEST_WEAK = re.compile(r"(вопрос\w*|задач\w*|что\s+оста\w+)", re.IGNORECASE)
_WIDE_FILE = re.compile(r"(файл\w*|верси\w*|документ\w*)", re.IGNORECASE)


def _norm(text: Optional[str]) -> str:
    return (text or "").replace("ё", "е").replace("Ё", "Е")


def _object_classes(t: str) -> tuple:
    """Какие классы объекта названы СЛОВАМИ:
    `(протокол, дайджест-однозначно, дайджест-слабо, неоднозначный)`.

    «итоги / резюме / сводка» считаем протоколом только рядом со словом про встречу:
    «итоги месяца» и «резюме кандидата» — не наш документ."""
    prot = bool(_WIDE_PROTOCOL.search(t)) or (
        bool(_WIDE_SUMMARY.search(t)) and bool(_WIDE_MEETING.search(t)))
    dig_strong = bool(_WIDE_DIGEST_STRONG.search(t))
    dig_weak = bool(_WIDE_DIGEST_WEAK.search(t))
    amb = bool(_WIDE_FILE.search(t))
    return prot, dig_strong, dig_weak, amb


def _digest_named(t: str) -> bool:
    """Назван ли ДАЙДЖЕСТ. Однозначная формулировка — сама по себе; голые
    «вопросы/задачи/что осталось» — только вместе с маркером просьбы (ревью-1 🔴-1)."""
    _, dig_strong, dig_weak, _ = _object_classes(t)
    return dig_strong or (dig_weak and looks_like_request(t))


def should_ask_ai(text: Optional[str], *, allow_bare_file: bool = True,
                  reply_surface: Optional[str] = None) -> bool:
    """Есть ли смысл платить за вызов модели на этом сообщении?

    Пред-фильтр, а НЕ понимание. Гейтит по ОБЪЕКТУ, а не по глаголу:
      1. текст не пустой и не длиннее потолка (длинная простыня — это пересланный
         протокол или пачка правок, а не просьба);
      2. назван НАШ документ. Однозначно названный («протокол», «открытые вопросы»,
         «дайджест», «висяки») — этого достаточно: просьба ли это, решает модель.
      3. слабая основа («вопросы / задачи / что осталось») и неоднозначный объект
         («файл / версия / документ») дополнительно требуют МАРКЕРА ПРОСЬБЫ — без
         него это обычная переписка людей про задачи, и звать модель незачем ни за
         деньги, ни за секунды в цикле листенера (ревью-1 🔴-1, ревью-2 🟡-3).

    🔴 Ремонт возобновления. Раньше маркер просьбы был условием для ВСЕХ объектов, и
    это возвращало список глаголов на шаг раньше модели: «а можно протокол?»,
    «высылай протокол», «мне бы протокол последней встречи», «список открытых вопросов
    в студию» словарём не ловятся и до модели не доходили — то есть критерий «ИИ
    определяет намерение» исполнялся только среди фраз, которые словарь уже признал
    просьбой. Инверсия снята: у однозначного объекта решает модель.
    Голый «файл / версия / документ» без контекста ответа даёт None при ЛЮБОМ ответе
    модели (инвариант Ф1) — платить за предрешённый исход не за что."""
    t = _norm(text).strip()
    if not t or len(t) > _MAX_TEXT_LEN_FOR_AI:
        return False
    prot, dig_strong, dig_weak, amb = _object_classes(t)
    if prot or dig_strong:
        return looks_like_request(t) or looks_like_a_request_in_shape(t)
    if dig_weak:
        # Голая основа «вопросы / задачи / что осталось» — только вместе с маркером
        # просьбы (ревью-1 🔴-1). Сузить до глагола отправки НЕЛЬЗЯ: «напомни, что
        # осталось по прошлой встрече» — законная просьба, названная в самом плане.
        # Плата за это — «напомни Игорю про задачи» доходит до модели; отличить их
        # кодом невозможно, и второй пояс здесь — верификация артефакта плюс
        # инструкция модели молчать при сомнении (остаток объявлен в долгах).
        return looks_like_request(t)
    return bool(amb and allow_bare_file and reply_surface in ("protocol", "digest")
                and looks_like_request(t))


def may_be_request(text: Optional[str], *, reply_surface: Optional[str] = None,
                   allow_bare_file: bool = True) -> bool:
    """Дешёвый детерминированный пред-чек ДЛЯ РОУТА: стоит ли вообще идти дальше.

    Ни сети, ни диска — только регулярки. Роут спрашивает это ПЕРЕД чтением реестра
    серий и перед разбором: так дорогое (YAML + возможный вызов модели) не платится
    на обычной переписке. True, если сработал бы быстрый путь ЛИБО есть смысл звать
    модель."""
    t = _norm(text)
    if not t.strip():
        return False
    fast = _detect_by_regex(t, reply_surface=reply_surface, allow_bare_file=allow_bare_file)
    if fast:
        return True
    return should_ask_ai(t, allow_bare_file=allow_bare_file, reply_surface=reply_surface)


