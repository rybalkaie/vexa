# -*- coding: utf-8 -*-
"""ISS-45: детект просьбы «пришли артефакт» — переотправить протокол ИЛИ дайджест
открытых вопросов по запросу участника, вместо глухого «🤔 Эту часть не понял».

Раньше движок разбора reply знал только два класса — «статус задачи» и «правка
текста»; просьба самому боту прислать файл не тот и не другой → фолбэк «не понял»
(владелец 23.07: «чуть-чуть шаг в сторону — и он не понимает ничего»). Этот модуль
даёт УЗКИЙ детерминированный триггер: явный глагол отправки + объект. Только оба
сигнала вместе → интент; иначе None (не крадём статусы/правки, которые роутятся ниже).

Различаем ДВА артефакта:
  • protocol — «протокол / актуальную версию / версию файла / документ»;
  • digest   — «открытые вопросы / дайджест / вопросы к встрече / список вопросов».
Неоднозначное «файл» разрешаем по тому, на ЧТО отвечают (`reply_surface`): reply на
дайджест → digest, на протокол → protocol; контекста нет → protocol (главный документ).

stdlib-only (исполняется в listener-контексте, системный python3.9 без venv).
"""
from __future__ import annotations

import re
from typing import Optional

# Глагол «пришли мне»: пришли/пришлите, скинь/скиньте, сбрось, перешли, кинь, отправь,
# дай/дайте, покажи, повтори, «можешь скинуть/прислать/отправить». «ё»→«е» нормализуем.
_SEND_VERB = re.compile(
    r"(при[шс]л[иеёте]+|скин[ьте]+|сброс[ьте]+|перешл[иёе]+|кин[ьте]+|отправ|"
    r"да[йте]+\b|покаж|повтор|мож[её]шь\s+(?:скину|присла|отправ)|"
    r"мог[ул]\s+(?:бы\s+)?(?:ты\s+)?(?:скину|присла|отправ))",
    re.IGNORECASE)

# Объект — ПРОТОКОЛ. ТОЛЬКО явное слово «протокол». «версию файла / актуальную версию /
# сам файл / документ» сюда НЕ входят — фидбэк владельца 23.07: ответ на дайджест «Открытые
# вопросы» с «актуальную версию файла» бот слал протоколом, хотя слова «протокол» не было и
# отвечали на дайджест. «файл/версия» — неоднозначное, разрешается по контексту ответа ниже.
_OBJ_PROTOCOL = re.compile(r"протокол", re.IGNORECASE)

# Объект — ДАЙДЖЕСТ открытых вопросов.
_OBJ_DIGEST = re.compile(
    r"(открыт\w*\s+вопрос\w*|дайджест|список\s+вопрос\w*|вопрос\w*\s+к\s+встреч\w*|"
    r"открыт\w*\s+задач\w*)",
    re.IGNORECASE)

# Неоднозначная ссылка «файл / версия / актуальную версию» без слова протокол/дайджест —
# разрешаем по тому, на ЧТО отвечают (reply_surface); контекста нет → протокол (главный).
_OBJ_FILE = re.compile(r"(файл\w*|верси\w*|актуальн\w*\s+верси\w*)", re.IGNORECASE)


def detect_artifact_request(
    text: Optional[str], *, reply_surface: Optional[str] = None,
    allow_bare_file: bool = True,
) -> Optional[str]:
    """Что просят переслать: `"protocol"` | `"digest"` | `None`.

    `reply_surface` (`"protocol"`|`"digest"`|`None`) — на ЧТО отвечает человек;
    разрешает неоднозначное «пришли файл». Возвращаем интент ТОЛЬКО при связке
    «глагол отправки + объект» — иначе None (статус/правку не перехватываем).

    `allow_bare_file` — можно ли вообще считать интентом ГОЛЫЙ объект
    «файл/версия» (без слова «протокол» и без дайджест-формулировки). Ветка
    голого объекта проектировалась под reply: контекст ответа и разрешал
    двусмысленность. Когда серия пришла НЕ из реплая, а из привязки чата
    (ISS-52), разрешать нечем, и «пришли файл с ценами» / «дайте актуальную
    версию договора» — обычная рабочая переписка людей между собой, а не
    просьба к боту. Поэтому вызыватель передаёт `allow_bare_file=is_reply`:
    без реплая голый объект даёт None, а однозначные («протокол», открытые
    вопросы/дайджест) работают как раньше."""
    t = (text or "").replace("ё", "е").replace("Ё", "Е")
    if not _SEND_VERB.search(t):
        return None
    dig = bool(_OBJ_DIGEST.search(t))
    prot = bool(_OBJ_PROTOCOL.search(t))
    if dig and not prot:
        return "digest"
    if prot and not dig:
        return "protocol"
    if dig and prot:
        # Оба явно названы — по контексту ответа, иначе протокол (главный документ).
        return reply_surface if reply_surface in ("protocol", "digest") else "protocol"
    if allow_bare_file and _OBJ_FILE.search(t):
        # Голый «файл» — по тому, на что отвечают.
        return reply_surface if reply_surface in ("protocol", "digest") else "protocol"
    return None
