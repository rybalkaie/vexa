"""Разбор команд привязки: код в личке и `/привязать` в группе (Ф12, R8.1–R8.6).

ЗАЧЕМ ЭТОТ МОДУЛЬ. До Ф12 у бота не было НИ ОДНОЙ слэш-команды: всё
распознавалось свободной речью закрытыми парсерами (`correction_command`,
`mode_command`). Привязка — первая команда, которую человек набирает по
инструкции с экрана портала, слово в слово. Значит разбор обязан быть узким и
предсказуемым, а не «понимающим»: «привязать» в середине живой фразы командой
НЕ является, иначе бот начнёт заводить группы посреди разговора.

🔴 ПОЧЕМУ ПРИНИМАЕМ ДВА НАПИСАНИЯ КОМАНДЫ — `/привязать` И `/bind`.
Требование R8.6 называет русскую форму дословно, и она же нарисована в макете.
Но у бота ВКЛЮЧЁН privacy mode (решение владельца 05.08): в группе он получает
только реплаи на себя, упоминания и СЛЭШ-КОМАНДЫ, а командой Telegram считает
`/` + латиница/цифры/подчёркивание. Кириллическое `/привязать` под это
определение не подходит, и в группе оно может до бота просто НЕ ДОЕХАТЬ.
Поэтому русская форма остаётся главной (её видит человек на экране), а
латинская `/bind` — та, что гарантированно проходит privacy mode. Какая из них
доедет на живом сервере — проверяется только боем; долг записан в плане.

🔴 СУФФИКС `@ИМЯБОТА` СНИМАЕТСЯ ВСЕГДА. В группе Telegram дописывает его сам
(`/bind@AnzheeWatsonBot`), и разбор без этого молча не узнаёт собственную
команду ровно там, где она нужнее всего.

В журнал из этого модуля не уходит ничего: здесь проходит КОД привязки — пароль
на пятнадцать минут.
"""

from __future__ import annotations

import re
from typing import NamedTuple, Optional

# Ровно шесть цифр — столько выдаёт портал (`LINK_CODE_LENGTH`). Расхождение
# этого числа с порталом означало бы отказ на верном коде.
CODE_LENGTH = 6

#: Что считается кодом, когда человек прислал его ОТДЕЛЬНЫМ сообщением.
#: Разделители внутри (пробелы, тире, точки) прощает уже портал — здесь только
#: грубый признак «это похоже на код», чтобы не гнать в сеть каждую реплику.
_BARE_CODE = re.compile(r"^[\d\s.\-_]{%d,%d}$" % (CODE_LENGTH, CODE_LENGTH * 3))

#: Команда: `/привязать`, `/bind`, с необязательным `@botname` и аргументом.
_COMMAND = re.compile(
    r"^/(?P<name>привязать|bind|start)(?:@[A-Za-z0-9_]{1,32})?(?:\s+(?P<arg>.+))?$",
    re.IGNORECASE,
)


class BindCommand(NamedTuple):
    """Что человек попросил.

    kind:
      * ``"code"``  — прислал код привязки (аргументом команды или отдельным
        сообщением). ``value`` — сырая строка кода, разбирать её будет портал:
        правила «что считается кодом» живут в ОДНОМ месте, и это не бот.
      * ``"group"`` — попросил привязать ЭТОТ чат. ``value`` — код компании,
        если назвал его, иначе ``None``.
      * ``"start"`` — `/start`, то есть «объясни, что делать».
    """

    kind: str
    value: Optional[str] = None


def parse_bind_command(
    text: str, *, direct: bool, known: bool = False
) -> Optional[BindCommand]:
    """Разобрать сообщение. ``None`` — «это не про привязку».

    ``direct`` — сообщение пришло в ЛИЧКУ. Именно в личку, а не «в личку
    доверенного лица»: разбор судит ВИД ЧАТА, и спрашивать это надо у самого
    сообщения (`chat.type == "private"`). Ф12 первым заходом спросила у функции
    доверия — та у незнакомца отвечает «нет», признак лички становился ложью, и
    непривязанный сотрудник (единственный адресат фазы) получал молчание.

    ``known`` — бот УЖЕ знает, кто это (владелец либо опознанный сотрудник).

    🔴 ГОЛЫЕ ШЕСТЬ ЦИФР СЧИТАЮТСЯ КОДОМ ТОЛЬКО В ЛИЧКЕ И ТОЛЬКО ОТ НЕЗНАКОМЦА.
    В группе люди пишут числа постоянно («переносим на 141500», номер счёта,
    сумма), и принимать их за код значило бы на каждом таком сообщении ходить в
    портал и получать промах — то есть чужими руками выбивать человеку
    блокировку по счётчику попыток. Ровно та же беда живёт и в личке ОПОЗНАННОГО
    человека: владелец пишет боту «141500» про время, роут привязки стоит первым
    и съедает сообщение, отвечая «такого кода не знаю». Поэтому у знакомого
    голые цифры кодом не считаются — ему привязка не нужна, а если всё же нужна
    (переезд на другой аккаунт), остаётся явная форма `/привязать 482913`.

    🔴 `/привязать` В ЛИЧКЕ — ЭТО НЕ ПРИВЯЗКА ГРУППЫ. Личка группой не
    является; там команда без аргумента означает «хочу привязаться», и её ведёт
    ветка кода (человек пришёл по инструкции, но перепутал шаг).
    """
    raw = (text or "").strip()
    if not raw:
        return None

    matched = _COMMAND.match(raw)
    if matched:
        name = (matched.group("name") or "").lower()
        arg = (matched.group("arg") or "").strip() or None
        if name == "start":
            return BindCommand(kind="start")
        # `/привязать 482913` — человек прислал код вместе с командой. Признак
        # один: аргумент похож на код. Всё прочее в группе — код компании.
        if arg and _BARE_CODE.match(arg):
            return BindCommand(kind="code", value=arg)
        if direct:
            # В личке команда без кода — просьба объяснить, а не привязка чата.
            return BindCommand(kind="start") if arg is None else BindCommand(kind="code", value=arg)
        return BindCommand(kind="group", value=arg)

    if (
        direct
        and not known
        and _BARE_CODE.match(raw)
        and sum(ch.isdigit() for ch in raw) == CODE_LENGTH
    ):
        return BindCommand(kind="code", value=raw)

    return None
