# -*- coding: utf-8 -*-
"""Ф2 (ISS-51…55): разбор ЯВНОЙ команды «режим открытых вопросов серии».

Владелец набирает (или диктует) короткую команду — она одинакова каждый раз и в
обычной переписке не встречается:

    режим шпаргалка              — эта серия (чат, где дана команда) → шпаргалка
    режим накопление             — эта серия → накопление
    режим шпаргалка Директорат   — названная серия (форма для лички)
    режим накопление anzhee-direktorat
    режим                        — показать текущий режим серии этого чата
    режим Директорат             — показать режим названной серии

Плюс закрытый список формулировок из плана (пункты 1 и 4 Фазы 2):

    эта серия — накопление / эта серия — шпаргалка
    серию <имя> — шпаргалка / серию <имя> — накопление
    в каком режиме эта серия

**И больше ничего.** Сообщение либо совпадает с одной из форм ЦЕЛИКОМ, либо это
не команда (`None`) — роут молча уступает её роутам ниже.

Почему так, а не «понимать язык». Предыдущая версия угадывала свободную речь
самодельной морфологией (9 регулярок, 179 строк): из 23 живых формулировок
владельца она понимала 9, до записи в реестр доходило 5, ШЕСТЬ просьб «выключи
накопление» («не надо больше копить», «без накопления») распознавались как
ВКЛЮЧИ накопление, а 8 из 10 бытовых фраз рабочей группы («давайте копить
вопросы к следующей встрече») перехватывались и заставляли бота вываливать в
групповой чат список внутренних имён всех серий. Детерминированный парсер
свободную речь не тянет; свободную речь план сам отдаёт Фазе 6 (ИИ-разбор), где
она и будет разобрана как надо. Здесь остаётся быстрый и предсказуемый вход,
который владелец набирает не думая.

Отсюда же и правило про отрицания: «не надо больше копить», «без накопления»,
«хватит копить» — НЕ команды (`None`). Либо форма понята точно, либо не понята
вовсе; «понял наоборот» исключено по построению.

Модуль импортируется из `meetings_listener.py` (venv-cli без pyannote/torch),
поэтому stdlib-only, как соседний `correction_command.py` / `protocol_command.py`.
"""
from __future__ import annotations

import re
from typing import NamedTuple, Optional

# Значения совпадают с `registry.VALID_OPEN_QUESTIONS_MODES`. Дублируются
# константами, а не импортом: парсер обязан оставаться stdlib-only и грузиться
# в листенере даже когда реестр (pyyaml) недоступен. Расхождение ловит тест.
CARRY = "carry"
LAST_ONLY = "last-only"

# Ссылка на серию длиннее этого — не имя серии, а чей-то текст: команду не
# признаём. Иначе `series_ref` уезжает дословно в ответ бота, ответ перестаёт
# влезать в лимит Telegram (4096), `sendMessage` возвращает ошибку — и человек
# не видит НИЧЕГО. Самый длинный slug боевого реестра — 40 символов.
MAX_SERIES_REF = 120


class ModeCommand(NamedTuple):
    action: str       # "set" | "query"
    mode: str         # "carry" | "last-only"; для query — ""
    series_ref: str   # явное имя/slug серии или "" (серия из контекста чата/реплая)


# Управляющие и невидимые символы (в т.ч. RTL-override): вырезаем целиком.
# Они не исполняются, но попадали в `series_ref`, ломали резолв серии и уезжали
# в ответ бота, где ломали отображение его собственного сообщения.
_INVISIBLE_RE = re.compile(
    "[\u0000-\u0008\u000b-\u001f\u007f-\u009f\u200b-\u200f"
    "\u202a-\u202e\u2060-\u2064\u2066-\u206f\ufeff]"
)

# Хвостовая пунктуация сообщения («режим шпаргалка!», «в каком режиме эта серия?»).
_TRAIL_PUNCT = " \t\n\r.!?…;,:"

# Тире всех сортов + двоеточие — разделитель «имя серии | режим».
_SEP = r"[-‐-―−:]"

# Слово режима. Небольшой набор окончаний: владелец диктует, и «режим
# шпаргалку» / «режим накопления» — та же команда, что «режим шпаргалка».
_MODE = r"(?P<carry>накоплени[еяию])|(?P<last>шпаргалк[ауие])"

# --- Закрытый список форм. Каждая матчит сообщение ЦЕЛИКОМ (^…$). ---

# Основная форма: «режим <режим> [<имя серии>]». Слэш допускается («/режим …»):
# в Telegram рука сама тянется поставить его перед командой.
_F_SET_KEYWORD = re.compile(rf"(?i)^/?режим\s+(?:{_MODE})(?:\s+(?P<ref>.+))?$")

# Плановая формулировка «эта серия — шпаргалка» (тире необязательно).
_F_SET_THIS = re.compile(rf"(?i)^эт[ау]\s+сери[яю]\s*{_SEP}?\s*(?:{_MODE})$")

# Плановая формулировка с именем: «серию Координация — шпаргалка».
_F_SET_NAMED = re.compile(rf"(?i)^сери[юя]\s+(?P<ref>.+?)\s*{_SEP}?\s*(?:{_MODE})$")

# Плановый вопрос «в каком режиме эта серия».
_F_QUERY_THIS = re.compile(r"(?i)^в\s+каком\s+режиме\s+эт[аи]\s+сери[яи]$")

# «режим» / «режим <имя серии>» — показать. Проверяется ПОСЛЕДНЕЙ: «режим
# шпаргалка» — это переключение, а не вопрос про серию по имени «шпаргалка».
_F_QUERY_KEYWORD = re.compile(r"(?i)^/?режим(?:\s+(?P<ref>.+))?$")


def _normalize(text: str) -> tuple:
    """Сообщение к сравнимому виду + признак «это вопрос».

    Возвращает `(текст без невидимых символов, лишних пробелов и хвостовой
    пунктуации; оканчивалось ли сообщение вопросительным знаком)`.
    """
    s = _INVISIBLE_RE.sub("", text)
    s = s.replace("\u00a0", " ")
    s = re.sub(r"\s+", " ", s).strip()
    is_question = s.rstrip(" \t.\u2026!;,").endswith("?")
    return s.strip(_TRAIL_PUNCT), is_question


def _clean_ref(raw: Optional[str]) -> Optional[str]:
    """Ссылка на серию из формы. `""` = серия из контекста чата, None = не команда.

    Имя серии берётся ЦЕЛИКОМ, как набрано: «Закупки и финпланирование
    (МПервый)», «1-на-1 с Татьяной Филипповой». Прошлая версия вычитала из имени
    служебные слова («и», «на») и не резолвила 2 из 4 человеческих имён боевого
    реестра — тех самых, которые бот сам печатает в подтверждениях.
    """
    if not raw:
        return ""
    ref = raw.strip().strip("«»\"'").strip(" -‐‑‒–—―−:.,").strip()
    if not ref:
        return ""
    if len(ref) > MAX_SERIES_REF:
        return None
    return ref


def _mode_of(m: "re.Match[str]") -> str:
    return CARRY if m.group("carry") else LAST_ONLY


def parse_mode_command(text: str) -> Optional[ModeCommand]:
    """`ModeCommand` или None, если это не наша команда (обычная переписка).

    None — нормальный и самый частый исход: листенер отдаёт сообщение роутам ниже.

    Дата `YYYY-MM-DD` в тексте команду НЕ гасит (в отличие от прошлой версии):
    три серии боевого реестра носят дату прямо в slug'е (`sales-quality-2026-05-27`),
    и гейт даты делал их недостижимыми — на корректную команду бот молчал.
    Красть команды коррекции протокола не с чего: те начинаются с «поправь /
    удали / протокол», а наши формы совпадают с сообщением целиком.
    """
    if not text or not text.strip():
        return None
    s, is_question = _normalize(text)
    if not s:
        return None

    m = _F_SET_KEYWORD.match(s)
    if m is None:
        m = _F_SET_THIS.match(s)
    if m is None:
        m = _F_SET_NAMED.match(s)
    if m is not None:
        # Вопросительный знак → это вопрос человека, а не приказ боту
        # («эта серия — шпаргалка?» ≠ «эта серия — шпаргалка»).
        if is_question:
            return None
        ref = _clean_ref(m.groupdict().get("ref"))
        return None if ref is None else ModeCommand("set", _mode_of(m), ref)

    if _F_QUERY_THIS.match(s):
        return ModeCommand("query", "", "")

    m = _F_QUERY_KEYWORD.match(s)
    if m is not None:
        ref = _clean_ref(m.group("ref"))
        return None if ref is None else ModeCommand("query", "", ref)
    return None
